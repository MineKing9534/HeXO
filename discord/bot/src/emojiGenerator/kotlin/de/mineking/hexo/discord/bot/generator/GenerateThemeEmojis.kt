package de.mineking.hexo.discord.bot.generator

import com.squareup.kotlinpoet.ClassName
import com.squareup.kotlinpoet.FileSpec
import com.squareup.kotlinpoet.FunSpec
import com.squareup.kotlinpoet.KModifier
import com.squareup.kotlinpoet.MAP
import com.squareup.kotlinpoet.MemberName
import com.squareup.kotlinpoet.ParameterizedTypeName.Companion.parameterizedBy
import com.squareup.kotlinpoet.PropertySpec
import com.squareup.kotlinpoet.STRING
import com.squareup.kotlinpoet.TypeSpec
import de.mineking.hexo.board.parse.notation.parseRectilinearNotation
import de.mineking.hexo.board.render.image.renderToImage
import de.mineking.hexo.board.render.image.theme.DefaultTheme
import java.awt.AlphaComposite
import java.awt.RenderingHints
import java.awt.geom.RoundRectangle2D
import java.awt.image.BufferedImage
import java.io.File
import javax.imageio.ImageIO

private const val EMOJI_MANAGER_PACKAGE = "de.mineking.discord.emoji"
private const val BOT_PACKAGE = "de.mineking.hexo.discord.bot"
private val enumType = ClassName(BOT_PACKAGE, "ThemeEmojis")

fun main(args: Array<String>) {
    require(args.size == 2) { "Expected Kotlin and resource output directories" }
    val kotlinDirectory = File(args[0])
    val resourceDirectory = File(args[1])

    // These directories belong exclusively to this generator; remove obsolete themes too.
    for (directory in listOf(kotlinDirectory, resourceDirectory)) {
        check(!directory.exists() || directory.deleteRecursively()) { "Cannot clear $directory" }
        check(directory.mkdirs()) { "Cannot create $directory" }
    }

    generateImages(resourceDirectory)
    generateEnum(kotlinDirectory)
}

private fun generateImages(directory: File) {
    val board = "x!/o".parseRectilinearNotation()

    val imageDirectory = directory.resolve("emoji/theme")
    check(imageDirectory.mkdirs())

    for (entry in DefaultTheme.entries) {
        val image = board.renderToImage(layoutRadius = 64.0, padding = 32, theme = entry.theme).withRoundedCorners()
        check(image.width > 0 && image.height > 0)
        check(ImageIO.write(image, "png", imageDirectory.resolve("${entry.name.lowercase()}.png")))
    }
}

private fun BufferedImage.withRoundedCorners(): BufferedImage {
    val result = BufferedImage(width, height, BufferedImage.TYPE_INT_ARGB)
    val graphics = result.createGraphics()
    try {
        graphics.setRenderingHint(RenderingHints.KEY_ANTIALIASING, RenderingHints.VALUE_ANTIALIAS_ON)
        val arcDiameter = minOf(width, height) * 0.5
        graphics.fill(RoundRectangle2D.Double(0.0, 0.0, width.toDouble(), height.toDouble(), arcDiameter, arcDiameter))
        graphics.composite = AlphaComposite.SrcIn
        graphics.drawImage(this, 0, 0, null)
    } finally {
        graphics.dispose()
    }
    return result
}

private fun generateEnum(directory: File) {
    val enum = TypeSpec.enumBuilder("ThemeEmojis")
        .addSuperinterface(ClassName(EMOJI_MANAGER_PACKAGE, "EmojiProvider"))
        .addSuperinterface(ClassName(EMOJI_MANAGER_PACKAGE, "EmojiKey"))

    DefaultTheme.entries.forEach { enum.addEnumConstant(it.name) }

    enum.addProperty(
        PropertySpec.builder("discordName", STRING, KModifier.OVERRIDE)
            .initializer("name.lowercase()")
            .build(),
    )

    enum.addFunction(
        FunSpec.builder("getImage")
            .addModifiers(KModifier.OVERRIDE)
            .returns(ClassName("net.dv8tion.jda.api.entities", "Icon"))
            .addStatement("return %M()", MemberName(BOT_PACKAGE, "readEmoji"))
            .build(),
    )

    enum.addType(
        TypeSpec.companionObjectBuilder()
            .addSuperinterface(ClassName(EMOJI_MANAGER_PACKAGE, "EmojiRegistrar"))
            .addProperty(
                PropertySpec.builder("namespace", STRING, KModifier.OVERRIDE)
                    .initializer("%S", "theme")
                    .build(),
            )
            .addProperty(
                PropertySpec.builder("emojis", MAP.parameterizedBy(enumType, enumType), KModifier.OVERRIDE)
                    .initializer("entries.associateWith { it }")
                    .build(),
            )
            .build(),
    )

    FileSpec.builder(BOT_PACKAGE, "ThemeEmojis")
        .addFileComment("Generated by generateThemeEmojis. Do not edit.")
        .addType(enum.build())
        .build()
        .writeTo(directory)
}
